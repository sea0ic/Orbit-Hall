// ── Fallback procedural star field ────────────────────────────────────────────
function genFallbackStars(n = 8000) {
  const s = []; let seed = 0xdeadbeef;
  const rnd = () => { seed = (Math.imul(seed,1664525)+1013904223)|0; return (seed>>>0)/0x100000000; };
  for (let i = 0; i < n; i++) {
    const ra = rnd()*24, dec = (Math.asin(rnd()*2-1)*180)/Math.PI;
    const u = rnd();
    const mag = u<.03?1+rnd()*2.5 : u<.15?3.5+rnd()*1.5 : u<.55?5+rnd()*1.5 : 6.5+rnd()*1.5;
    s.push({ ra, dec, mag, ci: rnd()*1.8-0.3 });
  }
  return s;
}
