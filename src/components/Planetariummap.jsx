function altToScreenY(alt, camAlt, cy, scale) {
  const rel = Math.max(-88, Math.min(88, alt - camAlt));
  return cy - Math.tan(rel * D2R) * scale;
}

function horizonScreenY(camAlt, cy, scale) {
  return cy + Math.tan(camAlt * D2R) * scale;
}

function azDelta(a, camAz) {
  return ((a - camAz + 540) % 360) - 180;
}

function ridgeHeight(az) {
  const r = az * D2R;
  let h = 2.2
        + 1.50 * Math.sin(r * 1.7 + 0.7)
        + 0.90 * Math.sin(r * 3.9 + 2.1)
        + 0.45 * Math.sin(r * 8.3 + 4.2)
        + 0.22 * Math.sin(r * 17.1 + 1.3);
  h = Math.max(0.4, h);
  for (let i = 0; i < TREES.length; i++) {
    const [t, th, sig] = TREES[i];
    const d = azDelta(az, t);
    h += th * Math.exp(-(d * d) / (2 * sig * sig));
  }
  return h;
}

function drawSky(ctx, W, H, camAlt, cy, scale, horizonY) {
  const yZenith = altToScreenY(90, camAlt, cy, scale);
  const span = horizonY - yZenith || 1;

  const sky = ctx.createLinearGradient(0, yZenith, 0, horizonY);
  for (let i = 0; i < SKY_STOPS.length; i++) {
    const [alt, color] = SKY_STOPS[i];
    const t = (altToScreenY(alt, camAlt, cy, scale) - yZenith) / span;
    sky.addColorStop(Math.max(0, Math.min(1, t)), color);
  }
  ctx.fillStyle = sky;
  ctx.fillRect(0, 0, W, H);

  // Light-pollution glow hugging the horizon.
  const glowH = Math.max(26, 7 * D2R * scale);
  const glow = ctx.createLinearGradient(0, horizonY, 0, horizonY - glowH);
  glow.addColorStop(0,    'rgba(140,164,205,0.16)');
  glow.addColorStop(0.45, 'rgba(90,114,155,0.055)');
  glow.addColorStop(1,    'rgba(90,114,155,0)');
  ctx.fillStyle = glow;
  ctx.fillRect(0, horizonY - glowH, W, glowH);
}

function drawGround(ctx, W, H, camAz, camAlt, fov, cx, cy, scale, horizonY) {
  if (horizonY > H + 2) return;

  const cosAlt = Math.cos(camAlt * D2R);
  const half = Math.min(80, Math.atan((W * 0.78) * cosAlt / scale) / D2R + 4);
  const steps = 150;

  const pts = [];
  for (let i = 0; i <= steps; i++) {
    const az = camAz - half + (2 * half * i) / steps;
    const x = cx + (Math.tan(azDelta(az, camAz) * D2R) / cosAlt) * scale;
    pts.push({ x, y: horizonY - ridgeHeight(az) * D2R * scale });
  }

  ctx.globalAlpha = 1;
  ctx.beginPath();
  ctx.moveTo(-60, H + 80);
  for (let i = 0; i < pts.length; i++) ctx.lineTo(pts[i].x, pts[i].y);
  ctx.lineTo(W + 60, H + 80);
  ctx.closePath();

  const ground = ctx.createLinearGradient(0, horizonY, 0, H);
  ground.addColorStop(0,   '#070a10');
  ground.addColorStop(0.45,'#04060b');
  ground.addColorStop(1,   '#020306');
  ctx.fillStyle = ground;
  ctx.fill();
}


