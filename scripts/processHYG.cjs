/**
 * processHYG.cjs
 *
 * Run once locally to convert hygdata_v41.csv into a compact JS module.
 * Usage:  node scripts/processHYG.cjs
 *
 * Input:  scripts/hygdata_v41.csv
 * Output: src/data/hygStars.js
 */

const fs   = require('fs');
const path = require('path');

const INPUT  = path.join(__dirname, 'hygdata_v41.csv');
const OUTPUT = path.join(__dirname, '..', 'src', 'data', 'hygStars.js');

const MAG_LIMIT = 8.0;

// ── Quote-aware CSV row parser ────────────────────────────────────────────────
// HYG quotes the header and any field that contains a comma, so a naive split
// would corrupt both the column map and proper names such as "Barnard's Star".
function parseCSVLine(line) {
  const out = [];
  let cur = '';
  let inQuotes = false;

  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (inQuotes) {
      if (ch === '"') {
        if (line[i + 1] === '"') { cur += '"'; i++; }
        else inQuotes = false;
      } else {
        cur += ch;
      }
    } else if (ch === '"') {
      inQuotes = true;
    } else if (ch === ',') {
      out.push(cur);
      cur = '';
    } else if (ch !== '\r') {
      cur += ch;
    }
  }
  out.push(cur);
  return out;
}

// ── Read CSV ──────────────────────────────────────────────────────────────────
console.log('Reading HYG catalog...');

if (!fs.existsSync(INPUT)) {
  console.error('\nERROR: Cannot find ' + INPUT);
  console.error('Place hygdata_v41.csv in the scripts/ folder.\n');
  process.exit(1);
}

const raw    = fs.readFileSync(INPUT, 'utf8');
const lines  = raw.split('\n');
const header = parseCSVLine(lines[0]).map(h => h.trim());

const col = {};
header.forEach((name, i) => { col[name] = i; });

console.log('CSV columns detected: ' + Object.keys(col).length);

for (const required of ['ra', 'dec', 'mag']) {
  if (col[required] === undefined) {
    console.error('\nERROR: missing "' + required + '" column. Header was:');
    console.error(header.join(', '));
    process.exit(1);
  }
}

// ── Process rows ──────────────────────────────────────────────────────────────
console.log('Processing stars with magnitude <= ' + MAG_LIMIT + '...');

const stars = [];
let skipped = 0;
let solSkipped = 0;

for (let i = 1; i < lines.length; i++) {
  const line = lines[i].replace(/\r$/, '');
  if (!line) continue;

  const p = parseCSVLine(line);

  const ra  = parseFloat(p[col['ra']]);
  const dec = parseFloat(p[col['dec']]);
  const mag = parseFloat(p[col['mag']]);

  if (isNaN(ra) || isNaN(dec) || isNaN(mag)) { skipped++; continue; }
  if (mag > MAG_LIMIT) continue;

  const proper = (p[col['proper']] || '').trim();
  const dist   = parseFloat(p[col['dist']]);

  // The Sun (Sol) sits at RA 0h / Dec 0 in the catalogue and is never "up"
  // at night; including it would paint a huge fake star at the equinox.
  if (proper === 'Sol' || dist === 0) { solSkipped++; continue; }

  const ci     = parseFloat(p[col['ci']]);
  const hip    = parseInt(p[col['hip']]  || '0', 10);
  const spect  = (p[col['spect']] || '').trim().slice(0, 6);
  const con    = (p[col['con']]   || '').trim();
  const absMag = parseFloat(p[col['absmag']]);

  const entry = {
    ra:  Math.round(ra  * 100000) / 100000,
    dec: Math.round(dec * 100000) / 100000,
    mag: Math.round(mag * 100) / 100,
    ci:  isNaN(ci) ? 0.6 : Math.round(ci * 100) / 100,
  };

  if (hip > 0)                    entry.hip  = hip;
  if (proper)                     entry.name = proper;
  if (con)                        entry.con  = con;
  if (spect)                      entry.sp   = spect;
  if (!isNaN(dist) && dist > 0)   entry.dist = Math.round(dist * 10) / 10;
  if (!isNaN(absMag))             entry.am   = Math.round(absMag * 10) / 10;

  stars.push(entry);
}

stars.sort((a, b) => a.mag - b.mag);

const named  = stars.filter(s => s.name).length;
const total  = stars.length;

console.log('');
console.log('  Stars kept (mag <= ' + MAG_LIMIT + '): ' + total.toLocaleString());
console.log('  Named stars:                   ' + named);
console.log('  Rows skipped (bad data):       ' + skipped);
console.log('  Sun rows dropped:              ' + solSkipped);

if (total === 0) {
  console.error('\nERROR: no stars parsed — check the CSV header/format.');
  process.exit(1);
}

// ── Write output ──────────────────────────────────────────────────────────────
console.log('\nWriting src/data/hygStars.js ...');

const jsonStr = JSON.stringify(stars);

const output = `/**
 * HYG Star Catalog — auto-generated by scripts/processHYG.cjs
 * Source: HYG Database v4.1 (Hipparcos + Yale + Gliese combined)
 * License: MIT — https://github.com/astronexus/HYG-Database
 *
 * ${total.toLocaleString()} stars · magnitude <= ${MAG_LIMIT}
 * Generated: ${new Date().toISOString().slice(0, 10)}
 *
 * Fields per star:
 *   ra   — right ascension in decimal hours (0–24)
 *   dec  — declination in degrees
 *   mag  — apparent visual magnitude
 *   ci   — B-V color index (drives star color in renderer)
 *   hip  — Hipparcos ID (optional)
 *   name — proper name e.g. "Sirius" (optional)
 *   con  — IAU constellation abbrev e.g. "Ori" (optional)
 *   sp   — spectral type e.g. "A0V" (optional)
 *   dist — distance in parsecs (optional)
 *   am   — absolute magnitude (optional)
 *
 * DO NOT EDIT. Re-run scripts/processHYG.cjs to regenerate.
 */

const _raw = ${jsonStr};

/** All ${total.toLocaleString()} stars sorted brightest-first */
export const HYG_STARS = _raw;

/** Named stars only (${named} entries) */
export const HYG_NAMED = _raw.filter(s => s.name);

/** Bright stars mag <= 3.5 — for constellation line lookups */
export const HYG_BRIGHT = _raw.filter(s => s.mag <= 3.5);
`;

fs.writeFileSync(OUTPUT, output, 'utf8');

const sizeKB = Math.round(fs.statSync(OUTPUT).size / 1024);
console.log('Done.  File size: ' + sizeKB + ' KB  (' + Math.round(sizeKB/1024*10)/10 + ' MB)');
console.log('');
console.log('Next: run  npm run dev  — the new star field loads automatically.');
